    /** Stopped by the shutdown of the application. */
    static class InterruptedRunException extends RuntimeException {

        InterruptedRunException() {
            super("Stopped: the application is shutting down");
        }
    }

    /** A stock the agents work on. */
    private static final class Work {
        final Outcome step;
        final long candidateId;
        final Position position;
        Double close;
        LocalDate priceDate;
        Scorecards cards;
        Map<String, Object> summary;
        Double technicalRules;
        String fundamentalDossier;
        String technicalDossier;
        PortfolioAgents.Outcome<FundamentalAnswer> fundamental;
        PortfolioAgents.Outcome<TechnicalAnswer> technical;
        double fundamentalFinal;
        boolean fundamentalPass;
        Double technicalFinal;
        String technicalStance;
        TradePlan plan;
        String planSource;
        Kelly kelly;
        final List<String> flags = new ArrayList<>();

        Work(Outcome step, long candidateId, Position position) {
            this.step = step;
            this.candidateId = candidateId;
            this.position = position;
        }

        String ticker() {
            return step.stock().ticker();
        }

        boolean held() {
            return step.held();
        }
    }

    /** The run's notes (report). */
    private static final class Notes {
        final List<String> messages = new java.util.concurrent.CopyOnWriteArrayList<>();

        void add(String message) {
            messages.add(message);
        }
    }

    public void run(UUID id) {
        RunParameters p = repository.parameters(id)
                .orElseThrow(() -> new IllegalStateException("Portfolio analysis run " + id + " not found"));
        UsageMeter meter = new UsageMeter(id, p.budgetUsd(), repository::insertUsage);
        Notes notes = new Notes();
        try {
            execute(p, meter, notes);
        } catch (InterruptedRunException e) {
            saveQuietly(id, meter, notes);
            jobs.finish(id, IngestionJobStatus.FAILED, "Interrupted", e.getMessage(), null);
        } catch (RuntimeException e) {
            log.error("portfolio analysis run {} failed", id, e);
            notes.add("The run failed: " + message(e));
            saveQuietly(id, meter, notes);
            jobs.finish(id, IngestionJobStatus.FAILED, "Failed", message(e), null);
        }
    }

    private void execute(RunParameters p, UsageMeter meter, Notes notes) {
        UUID id = p.id();
        Exchange exchange = Exchange.of(p.exchange());

        // ---- the portfolio
        jobs.running(id, "Reading the portfolio (Portfolio > Position)");
        Portfolio portfolio = portfolios.portfolio(p.userId());
        double cash = portfolio.summary().cash() + p.addedCapital();
        double market = portfolio.summary().marketTotal();
        double capital = market + cash;
        Map<String, Position> positions = new LinkedHashMap<>();
        portfolio.positions().forEach(x -> positions.put(x.ticker(), x));
        Map<String, Object> capitalDoc = new LinkedHashMap<>();
        capitalDoc.put("cash", portfolio.summary().cash());
        capitalDoc.put("addedCapital", p.addedCapital());
        capitalDoc.put("marketValue", market);
        capitalDoc.put("averageValue", portfolio.summary().averageTotal());
        capitalDoc.put("total", capital);
        capitalDoc.put("positions", positions.size());
        capitalDoc.put("priced", portfolio.summary().priced());
        capitalDoc.put("totalInvestment", portfolio.summary().totalInvestment());
        capitalDoc.put("computedAt", portfolio.computedAt().toString());
        if (capital <= 0) {
            repository.saveStart(id, capitalDoc, null);
            finish(id, meter, notes, IngestionJobStatus.FAILED, "Nothing to invest",
                    "The portfolio has no cash and no priced position, and no capital was added: set the cash on "
                            + "Portfolio > Position or add capital.");
            return;
        }
        if (portfolio.summary().priced() < positions.size()) {
            notes.add((positions.size() - portfolio.summary().priced()) + " position(s) have no stored price: they are "
                    + "kept as they are and left out of the capital.");
        }

        // ---- step 1 and step 2 (rules); a fundamental-only run reads no Technical (Score)
        boolean technicalSteps = p.technical();
        jobs.progress(id, technicalSteps
                ? "Step 1 and 2: the Fundamental (Score) and Technical (Score) of every company (Companies > Fundamentals)"
                : "Step 1: the Fundamental (Score) of every company (Companies > Fundamentals; fundamental only)",
                null, null);
        QuantScoreBoard.Board fundamentals = quantBoard.board(exchange.code());
        checkInterrupted();
        List<TechnicalScoreBoard.Score> technicalScores = technicalSteps ? technicalBoard.board(exchange.code()).scores()
                : List.of();
        checkInterrupted();
        Map<String, CompanyInfo> companies = repository.companies(exchange.code());
        Map<String, QuantScoreBoard.Score> fScores = new LinkedHashMap<>();
        fundamentals.scores().forEach(s -> fScores.put(s.ticker(), s));
        Map<String, TechnicalScoreBoard.Score> tScores = new LinkedHashMap<>();
        technicalScores.forEach(s -> tScores.put(s.ticker(), s));
        Function<String, Stock> stock = t -> {
            QuantScoreBoard.Score f = fScores.get(t);
            TechnicalScoreBoard.Score s = tScores.get(t);
            CompanyInfo c = companies.get(t);
            return new Stock(t, c == null ? t : c.companyName(), c == null ? null : c.sector(),
                    f == null ? null : f.overall(), f == null ? null : f.verdict(), s == null ? null : s.overall(),
                    s == null ? null : s.stance(), !technicalSteps ? null : s == null ? "No prices stored" : s.error());
        };
        List<String> universeTickers = p.selected() ? p.tickers() : new ArrayList<>(companies.keySet());
        List<Stock> universe = universeTickers.stream().map(stock).toList();
        Map<String, Stock> holdings = new LinkedHashMap<>();
        positions.keySet().forEach(t -> holdings.put(t, stock.apply(t)));
        AnalysisSteps.Limits limits = AnalysisSteps.Limits.of(p.maxStocks(), properties);
        AnalysisSteps.Result steps = AnalysisSteps.run(universe, positions.keySet(), holdings, limits, technicalSteps);
        Map<String, Object> funnel = new LinkedHashMap<>(steps.funnel());
        funnel.put("mode", p.mode());
        repository.saveStart(id, capitalDoc, funnel);

        // the stocks of the report: the candidates, every stock step 2 left out, step 1's near misses
        List<Work> works = new ArrayList<>();
        int nearMisses = limits.fundamentalKeep() * 2;
        for (Outcome o : steps.outcomes()) {
            Stock s = o.stock();
            boolean keep = o.passed() || p.selected() || AnalysisSteps.TECHNICAL_OUT.equals(o.stage())
                    || (o.fundamentalRank() != null && o.fundamentalRank() <= nearMisses);
            if (!keep) {
                continue;
            }
            String stage = o.passed() ? (o.held() ? "HELD" : "NOT_CHOSEN") : o.stage();
            List<String> flags = new ArrayList<>(o.flags());
            if (!o.passed() && o.reason() != null) {
                flags.add(o.reason());
            }
            Position pos = positions.get(s.ticker());
            long candidateId = repository.insertCandidate(id, s.ticker(), s.companyName(), s.sector(), o.held(),
                    pos == null ? null : positionDoc(pos, capital), pos == null ? null : pos.lastPrice(),
                    pos == null ? null : pos.priceDate(), s.fundamental(), s.fundamentalVerdict(), o.fundamentalRank(),
                    s.technical(), s.technicalStance(), o.technicalRank(), stage, flags);
            if (o.passed()) {
                Work w = new Work(o, candidateId, pos);
                w.flags.addAll(o.flags());
                works.add(w);
            }
        }
        int stepCandidates = (int) works.stream().filter(w -> !w.held()).count();
        if (stepCandidates == 0) {
            notes.add("No stock passed both rules steps" + (p.selected() ? " among the " + p.tickers().size()
                    + " selected" : "") + ": the analysis covers the holdings only.");
        }
        if (works.isEmpty()) {
            finish(id, meter, notes, IngestionJobStatus.INCOMPLETE, "Nothing to analyse",
                    "No stock passed the two rules steps and the portfolio holds no stock.");
            return;
        }

        // ---- the dossiers
        jobs.progress(id, "Dossiers of " + works.size() + " stocks (scorecards and preset summaries)", null, null);
        for (Work w : works) {
            dossiers(exchange, w, technicalSteps);
        }
        checkInterrupted();

        double reserve = properties.synthesisReserveUsd();
        ModelPrice agentPrice = screening.llm().price(screening.llm().agentModel());
        int maxTokens = properties.agentMaxTokens();
        List<String> fundamentalLessons = lessons.lessons(PortfolioAgents.FUNDAMENTAL);
        List<String> technicalLessons = lessons.lessons(PortfolioAgents.TECHNICAL);

        // ---- the fundamental agent (independent calls), then Reflection
        List<Work> withCards = works.stream().filter(w -> w.cards != null && w.cards.overall() != null).toList();
        AtomicInteger budgetSkipped = new AtomicInteger();
        List<PortfolioAgents.Outcome<FundamentalAnswer>> fOut = parallel(withCards, w -> {
            if (!meter.allows(agentPrice.cost(3_500, maxTokens), reserve)) {
                budgetSkipped.incrementAndGet();
                return PortfolioAgents.Outcome.<FundamentalAnswer>none(PortfolioAgents.FUNDAMENTAL,
                        "Cost budget reached");
            }
            return agents.fundamental(meter, w.ticker(), w.fundamentalDossier, w.cards.overall(), risk(w.cards),
                    fundamentalLessons, maxTokens);
        }, done -> progress(id, meter, "Fundamental agent: " + withCards.size() + " stocks (" + done + "/"
                + withCards.size() + ")"));
        for (int i = 0; i < withCards.size(); i++) {
            withCards.get(i).fundamental = fOut.get(i);
        }
        List<Work> fFlagged = withCards.stream().filter(w -> w.fundamental.original() != null
                && !w.fundamental.issues().isEmpty()).toList();
        List<PortfolioAgents.Outcome<FundamentalAnswer>> fReviewed = parallel(fFlagged, w -> {
            if (!meter.allows(agentPrice.cost(4_500, maxTokens), reserve)) {
                budgetSkipped.incrementAndGet();
                return w.fundamental;
            }
            return agents.reviewFundamental(meter, w.ticker(), w.fundamentalDossier, w.cards.overall(), risk(w.cards),
                    w.fundamental, maxTokens);
        }, done -> progress(id, meter, "Reflection: " + fFlagged.size() + " flagged fundamental answers (" + done + "/"
                + fFlagged.size() + ")"));
        for (int i = 0; i < fFlagged.size(); i++) {
            fFlagged.get(i).fundamental = fReviewed.get(i);
        }
        double w8 = properties.llmWeight();
        for (Work w : works) {
            double rules = w.cards == null || w.cards.overall() == null ? 0 : w.cards.overall();
            FundamentalAnswer a = w.fundamental == null ? null : w.fundamental.effective();
            if (w.cards == null || w.cards.overall() == null) {
                w.fundamentalFinal = 0;
                w.fundamentalPass = false;
                w.flags.add("No Fundamental (Score): the fundamental agent could not judge it");
            } else if (a == null || a.score() == null || a.verdict() == null) {
                w.fundamentalFinal = round1(rules);
                w.fundamentalPass = rules >= properties.minFundamentalScore();
            } else {
                w.fundamentalFinal = round1((1 - w8) * rules + w8 * a.score());
                w.fundamentalPass = "PASS".equals(a.verdict());
            }
        }
        checkInterrupted();

        // ---- the technical agent: the stocks the fundamental agent passed, and the holdings; then Reflection
        List<Work> timing = !technicalSteps ? List.of() : works.stream().filter(w -> w.summary != null
                && w.close != null && (w.held() || w.fundamentalPass)).toList();
        List<PortfolioAgents.Outcome<TechnicalAnswer>> tOut = parallel(timing, w -> {
            if (!meter.allows(agentPrice.cost(4_000, maxTokens), reserve)) {
                budgetSkipped.incrementAndGet();
                return PortfolioAgents.Outcome.<TechnicalAnswer>none(PortfolioAgents.TECHNICAL, "Cost budget reached");
            }
            return agents.technical(meter, w.ticker(), w.technicalDossier, w.technicalRules, w.close,
                    technicalLessons, maxTokens);
        }, done -> progress(id, meter, "Technical agent: " + timing.size() + " stocks (" + done + "/" + timing.size()
                + ")"));
        for (int i = 0; i < timing.size(); i++) {
            timing.get(i).technical = tOut.get(i);
        }
        List<Work> tFlagged = timing.stream().filter(w -> w.technical.original() != null
                && !w.technical.issues().isEmpty()).toList();
        List<PortfolioAgents.Outcome<TechnicalAnswer>> tReviewed = parallel(tFlagged, w -> {
            if (!meter.allows(agentPrice.cost(5_000, maxTokens), reserve)) {
                budgetSkipped.incrementAndGet();
                return w.technical;
            }
            return agents.reviewTechnical(meter, w.ticker(), w.technicalDossier, w.technicalRules, w.close, w.technical,
                    maxTokens);
        }, done -> progress(id, meter, "Reflection: " + tFlagged.size() + " flagged technical answers (" + done + "/"
                + tFlagged.size() + ")"));
        for (int i = 0; i < tFlagged.size(); i++) {
            tFlagged.get(i).technical = tReviewed.get(i);
        }
        int rulesPlans = 0;
        for (Work w : works) {
            if (w.summary == null || w.close == null) {
                continue;
            }
            TechnicalAnswer a = w.technical == null ? null : w.technical.effective();
            if (a != null && a.score() != null && a.stance() != null) {
                w.technicalFinal = round1((1 - w8) * w.technicalRules + w8 * a.score());
                w.technicalStance = a.stance();
                w.plan = TradePlan.ofModel(a.entry(), a.entryType(), a.target(), a.stopLoss(), w.close,
                        technical.ticks(), "AI", PortfolioAgents.TECHNICAL, "Technical agent (AI)");
                w.planSource = "AI";
            } else {
                w.technicalFinal = w.technicalRules;
                w.technicalStance = TechnicalScore.stance(w.technicalRules);
            }
            if (w.plan == null) {
                w.plan = bestRulesPlan(w.summary);
                w.planSource = w.plan == null ? null : "RULES";
                if (a != null && w.plan != null) {
                    rulesPlans++;
                }
            }
        }
        if (rulesPlans > 0) {
            notes.add(rulesPlans + " technical answer(s) gave no valid trade plan after the reflection: the best preset's "
                    + "rules levels are used.");
        }
        if (budgetSkipped.get() > 0) {
            notes.add(budgetSkipped.get() + " optional model call(s) skipped: the cost budget was reached (those stocks "
                    + "keep the rules' verdict).");
        }
        long noAnswer = works.stream().filter(w -> w.fundamental != null && w.fundamental.original() == null
                && w.fundamental.error() != null && !"Cost budget reached".equals(w.fundamental.error())).count()
                + works.stream().filter(w -> w.technical != null && w.technical.original() == null
                && w.technical.error() != null && !"Cost budget reached".equals(w.technical.error())).count();
        if (noAnswer > 0) {
            notes.add(noAnswer + " agent answer(s) were not usable: those stocks keep the rules' verdict.");
        }
        checkInterrupted();

        // ---- sizing (half-Kelly) and the ideas
        PortfolioAllocator.Limits allocLimits = new PortfolioAllocator.Limits(p.maxStocks(),
                properties.maxPositionWeight(), properties.maxSectorWeight(), properties.minPositionWeight(),
                properties.kellyFraction(), properties.lotSize());
        List<Idea> ideas = new ArrayList<>();
        for (Work w : works) {
            w.kelly = !technicalSteps ? PortfolioAllocator.kellyEven(w.fundamentalFinal, allocLimits)
                    : w.plan == null || w.plan.buy() == null || w.plan.sell() == null || w.plan.stopLoss() == null
                    ? PortfolioAllocator.kelly(w.fundamentalFinal, null, null, null, allocLimits)
                    : PortfolioAllocator.kelly(w.fundamentalFinal, w.plan.buy().price(), w.plan.stopLoss().price(),
                            w.plan.sell().price(), allocLimits);
            Double price = w.held() ? (w.position.lastPrice() == null ? null : w.position.lastPrice()) : w.close;
            double shares = w.held() ? w.position.shares() : 0;
            double value = w.held() && w.position.marketValue() != null ? w.position.marketValue() : 0;
            double order = technicalSteps ? (w.technicalFinal == null ? 0 : w.technicalFinal) : w.fundamentalFinal;
            ideas.add(new Idea(w.ticker(), w.step.stock().sector(), w.held(), price, shares, value, w.fundamentalPass,
                    w.technicalStance, order, w.kelly, technicalSteps));
        }
        Map<String, Proposal> fallback = PortfolioAllocator.fallback(ideas, capital, allocLimits);

        // ---- synthesis (Opus)
        Map<String, Object> input = synthesisInput(exchange, p, capitalDoc, capital, works);
        Set<String> known = new HashSet<>();
        works.forEach(w -> known.add(w.ticker()));
        progress(id, meter, "Synthesis of the portfolio (" + synthesis.model() + ")");
        ModelPrice synthesisPrice = screening.llm().price(synthesis.model());
        boolean allowModel = meter.allows(synthesisPrice.cost(8_000 + works.size() * 450L, 3_000 + works.size() * 90L),
                0);
        PortfolioSynthesis.Result syn = synthesis.synthesize(meter, input, known, positions.keySet(), fallback,
                allowModel, properties.synthesisMaxTokens(), technicalSteps);
        if (syn.fallback() != null) {
            notes.add("Recommendations written without the synthesis model: " + syn.fallback());
        }
        Allocation allocation = PortfolioAllocator.allocate(ideas, syn.proposals(), syn.cashTarget(), capital, cash,
                allocLimits);
        allocation.notes().forEach(notes::add);

        // ---- save the report
        jobs.progress(id, "Saving the report", null, null);
        Map<String, PortfolioAllocator.Position> byTicker = new LinkedHashMap<>();
        allocation.positions().forEach(x -> byTicker.put(x.ticker(), x));
        Map<String, Integer> finalRank = new LinkedHashMap<>();
        for (int i = 0; i < allocation.positions().size(); i++) {
            finalRank.put(allocation.positions().get(i).ticker(), i + 1);
        }
        Map<String, List<Issue>> issues = new LinkedHashMap<>();
        issues.put(PortfolioAgents.FUNDAMENTAL, new ArrayList<>());
        issues.put(PortfolioAgents.TECHNICAL, new ArrayList<>());
        for (Work w : works) {
            if (w.fundamental != null) {
                issues.get(PortfolioAgents.FUNDAMENTAL).addAll(w.fundamental.issues());
            }
            if (w.technical != null) {
                issues.get(PortfolioAgents.TECHNICAL).addAll(w.technical.issues());
            }
            repository.saveAgents(w.candidateId, fundamentalDoc(w), technicalDoc(w), w.close, w.priceDate);
            PortfolioAllocator.Position pos = byTicker.get(w.ticker());
            Proposal proposal = syn.proposals().get(w.ticker());
            String stage;
            if (w.held()) {
                stage = "HELD";
            } else if (pos != null) {
                stage = "RECOMMENDED";
            } else if (!w.fundamentalPass) {
                stage = "FUNDAMENTAL_AI_OUT";
            } else if (technicalSteps && !"BUY".equals(w.technicalStance) && !"ACCUMULATE".equals(w.technicalStance)) {
                stage = "TECHNICAL_AI_OUT";
            } else {
                stage = "NOT_CHOSEN";
            }
            Map<String, Object> rec = null;
            if (pos != null) {
                rec = new LinkedHashMap<>(pos.toMap());
            } else if (allocation.skipped().containsKey(w.ticker()) || proposal != null) {
                rec = new LinkedHashMap<>();
                rec.put("proposedWeight", proposal == null ? null : proposal.targetWeight());
                rec.put("reason", proposal == null ? null : proposal.reason());
                rec.put("adjustments", allocation.skipped().getOrDefault(w.ticker(), List.of()));
            }
            String thesis = proposal != null && proposal.reason() != null ? proposal.reason() : bestThesis(w);
            repository.saveFinal(w.candidateId, stage, w.kelly == null ? null : w.kelly.toMap(),
                    pos == null ? null : pos.action(), rec, proposal == null ? null : proposal.conviction(), thesis,
                    w.flags, finalRank.get(w.ticker()));
        }
        List<PortfolioLessons.Learned> learned = lessons.learn(id, issues);

        Map<String, Object> synthesisDoc = new LinkedHashMap<>();
        synthesisDoc.put("executiveSummary", syn.executiveSummary());
        synthesisDoc.put("riskNotes", syn.riskNotes());
        synthesisDoc.put("cashTarget", syn.cashTarget());
        synthesisDoc.put("model", syn.model());
        synthesisDoc.put("fallback", syn.fallback());
        Map<String, Object> allocationDoc = new LinkedHashMap<>();
        allocationDoc.put("capital", allocation.capital());
        allocationDoc.put("cashBefore", allocation.cashBefore());
        allocationDoc.put("cashAfter", allocation.cashAfter());
        allocationDoc.put("cashWeightBefore", capital > 0 ? allocation.cashBefore() / capital : 0);
        allocationDoc.put("cashWeightAfter", allocation.cashTargetWeight());
        allocationDoc.put("sectorsBefore", allocation.sectorsBefore());
        allocationDoc.put("sectorsAfter", allocation.sectorsAfter());
        allocationDoc.put("buyValue", allocation.positions().stream().filter(x -> x.tradeValue() > 0)
                .mapToDouble(PortfolioAllocator.Position::tradeValue).sum());
        allocationDoc.put("sellValue", -allocation.positions().stream().filter(x -> x.tradeValue() < 0)
                .mapToDouble(PortfolioAllocator.Position::tradeValue).sum());
        allocationDoc.put("stocksBefore", positions.size());
        allocationDoc.put("stocksAfter", allocation.positions().stream().filter(x -> x.targetShares() > 0).count());
        allocationDoc.put("limits", Map.of("maxStocks", p.maxStocks(), "maxPositionWeight",
                properties.maxPositionWeight(), "maxSectorWeight", properties.maxSectorWeight(), "kellyFraction",
                properties.kellyFraction(), "lotSize", properties.lotSize(), "minPositionWeight",
                properties.minPositionWeight()));
        Map<String, Object> notesDoc = notesDoc(notes, meter, learned, fundamentalLessons, technicalLessons,
                fFlagged.size() + tFlagged.size());
        repository.saveResult(id, synthesisDoc, allocationDoc, allocation.checks(), notesDoc);
        repository.saveTotals(id, meter.total());

        long buys = allocation.positions().stream().filter(x -> "BUY".equals(x.action())).count();
        long sells = allocation.positions().stream().filter(x -> "SELL".equals(x.action())).count();
        String summary = String.format(Locale.ROOT, "%d stock(s) after the recommendations (%d new, %d sold), cash %.1f%%, "
                + "$%.2f", (long) allocation.positions().stream().filter(x -> x.targetShares() > 0).count(), buys, sells,
                allocation.cashTargetWeight() * 100, meter.spentUsd());
        boolean checksOk = allocation.checks().stream().allMatch(c -> Boolean.TRUE.equals(c.get("ok")));
        boolean degraded = syn.fallback() != null || budgetSkipped.get() > 0 || noAnswer > 0 || !checksOk;
        if (!checksOk) {
            notes.add("A limit check failed on the result: review the checks.");
            repository.saveNotes(id, notesDoc(notes, meter, learned, fundamentalLessons, technicalLessons,
                    fFlagged.size() + tFlagged.size()));
        }
        if (degraded) {
            jobs.finish(id, IngestionJobStatus.INCOMPLETE, summary, String.join(" ", notes.messages), null);
        } else {
            jobs.finish(id, IngestionJobStatus.SUCCEEDED, summary, null, null);
        }
        log.info("portfolio analysis run {} finished: {}", id, summary);
    }

