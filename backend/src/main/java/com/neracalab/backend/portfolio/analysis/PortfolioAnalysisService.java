    private <T, R> List<R> parallel(List<T> items, Function<T, R> fn, IntConsumer progress) {
        if (items.isEmpty()) {
            return List.of();
        }
        Semaphore slots = new Semaphore(Math.max(1, screening.llm().concurrency()));
        AtomicInteger done = new AtomicInteger();
        List<R> out = new ArrayList<>(items.size());
        try (ExecutorService pool = Executors.newVirtualThreadPerTaskExecutor()) {
            List<Future<R>> futures = new ArrayList<>(items.size());
            for (T item : items) {
                futures.add(pool.submit(() -> {
                    slots.acquire();
                    try {
                        return fn.apply(item);
                    } finally {
                        slots.release();
                        progress.accept(done.incrementAndGet());
                    }
                }));
            }
            for (Future<R> f : futures) {
                try {
                    out.add(f.get());
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                    pool.shutdownNow();
                    throw new InterruptedRunException();
                } catch (ExecutionException e) {
                    throw e.getCause() instanceof RuntimeException r ? r : new IllegalStateException(e.getCause());
                }
            }
        }
        return out;
    }

    private final AtomicLong lastProgress = new AtomicLong();

    private void progress(UUID id, UsageMeter meter, String stage) {
        long now = System.currentTimeMillis();
        long last = lastProgress.get();
        if (now - last < 1_000 && !stage.startsWith("Synthesis")) {
            return;
        }
        lastProgress.set(now);
        jobs.progress(id, String.format(Locale.ROOT, "%s · $%.3f", stage, meter.spentUsd()), null, null);
    }

    private void finish(UUID id, UsageMeter meter, Notes notes, IngestionJobStatus status, String stage,
                        String message) {
        saveQuietly(id, meter, notes);
        jobs.finish(id, status, stage, message, null);
    }

    private void saveQuietly(UUID id, UsageMeter meter, Notes notes) {
        try {
            repository.saveNotes(id, Map.of("messages", List.copyOf(notes.messages)));
            repository.saveTotals(id, meter.total());
        } catch (RuntimeException e) {
            log.warn("portfolio analysis run {}: the notes could not be saved: {}", id, e.toString());
        }
    }

    private static void checkInterrupted() {
        if (Thread.currentThread().isInterrupted()) {
            throw new InterruptedRunException();
        }
    }

    private static double round1(double v) {
        return Math.round(v * 10) / 10.0;
    }

    private static double round4(double v) {
        return Math.round(v * 10_000) / 10_000.0;
    }

    private static String message(Throwable e) {
        return e.getMessage() == null ? e.getClass().getSimpleName() : e.getMessage();
    }
