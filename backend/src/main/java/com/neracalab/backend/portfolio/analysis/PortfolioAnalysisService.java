    private void dossiers(Exchange exchange, Work w, boolean technicalSteps) {
        String ticker = w.ticker();
        try {
            w.cards = scorecards.scorecards(exchange.code(), ticker);
        } catch (RuntimeException e) {
            w.flags.add("Scorecards not readable: " + message(e));
        }
        if (!technicalSteps) {
            // fundamental only: no chart is read, the price is the latest close as Portfolio > Position shows it
            latestClose(exchange, w);
        } else try {
            w.summary = technical.summary(exchange.code(), ticker);
            w.technicalRules = TechnicalScore.of(w.summary).overall();
            Object close = w.summary.get("close");
            w.close = close instanceof Number n && n.doubleValue() > 0 ? n.doubleValue() : null;
            Object asOf = w.summary.get("asOfDate");
            w.priceDate = asOf == null ? null : LocalDate.parse(asOf.toString().substring(0, 10));
            if (w.technicalRules == null) {
                w.summary = null;
            }
        } catch (RuntimeException e) {
            w.summary = null;
        }
        if (technicalSteps && (w.summary == null || w.close == null)) {
            w.summary = null;
            w.flags.add("No Technical (Score): no timing or trade plan");
        }
        Map<String, Object> f = new LinkedHashMap<>();
        f.put("ticker", ticker);
        f.put("company", w.step.stock().companyName());
        f.put("sector", w.step.stock().sector());
        f.put("held", w.held());
        if (w.position != null) {
            f.put("position", Map.of("shares", w.position.shares(), "averagePrice", w.position.averagePrice(),
                    "gainLossPct", w.position.gainLossPct() == null ? "unknown" : round4(w.position.gainLossPct())));
        }
        if (w.cards != null) {
            f.put("fundamentalScore", w.cards.overall());
            f.put("verdict", w.cards.verdict());
            f.put("financialCompany", w.cards.financial());
            f.put("fiscalYear", w.cards.fiscalYear());
            List<Map<String, Object>> cards = new ArrayList<>();
            for (AgentCard c : w.cards.agents()) {
                Map<String, Object> m = new LinkedHashMap<>();
                m.put("agent", c.label());
                m.put("score", c.score());
                m.put("verdict", c.verdict());
                m.put("coverage", round4(c.coverage()));
                cards.add(m);
            }
            f.put("scorecards", cards);
            Map<String, Object> metrics = new LinkedHashMap<>();
            w.cards.metrics().forEach(m -> {
                if (m.value() != null) {
                    metrics.put(m.key(), round4(m.value()));
                }
            });
            f.put("metrics", metrics);
            f.put("metricUnits", "percent metrics are fractions (0.15 = 15%)");
        }
        w.fundamentalDossier = "STOCK FUNDAMENTAL DOSSIER\n" + json.writeValueAsString(f);
        if (w.summary != null) {
            Map<String, Object> t = new LinkedHashMap<>();
            t.put("ticker", ticker);
            t.put("held", w.held());
            if (w.position != null) {
                t.put("averagePrice", w.position.averagePrice());
            }
            t.put("close", w.close);
            t.put("asOfDate", w.summary.get("asOfDate"));
            t.put("technicalScore", w.technicalRules);
            t.put("technicalStance", TechnicalScore.stance(w.technicalRules));
            List<Map<String, Object>> presets = new ArrayList<>();
            if (w.summary.get("summaries") instanceof List<?> list) {
                for (Object o : list) {
                    if (o instanceof Map<?, ?> m) {
                        Map<String, Object> x = new LinkedHashMap<>();
                        x.put("preset", m.get("name"));
                        x.put("stance", m.get("stance"));
                        x.put("score", TechnicalScore.agentScore(m.get("score"), m.get("maxScore")));
                        x.put("buy", priceOf(m.get("buy")));
                        x.put("sell", priceOf(m.get("sell")));
                        x.put("stopLoss", priceOf(m.get("stopLoss")));
                        x.put("rewardRisk", m.get("rewardRisk"));
                        x.put("thesis", m.get("thesis"));
                        if (m.get("points") instanceof List<?> points) {
                            x.put("evidence", points.stream().limit(6).map(pt -> pt instanceof Map<?, ?> pm
                                    ? pm.get("tone") + ": " + pm.get("text") : String.valueOf(pt)).toList());
                        }
                        presets.add(x);
                    }
                }
            }
            t.put("presets", presets);
            t.put("caveats", w.summary.get("caveats"));
            w.technicalDossier = "STOCK TECHNICAL DOSSIER\n" + json.writeValueAsString(t);
        }
    }

    /** The latest stored close in the listing currency (a USD reporter's at the rate the price ingestion used). */
    private void latestClose(Exchange exchange, Work w) {
        try {
            positionsData.companyId(exchange.code(), w.ticker())
                    .flatMap(id -> positionsData.closes(id, exchange.currency(), 1).stream().findFirst())
                    .ifPresent(c -> {
                        w.close = c.price().doubleValue();
                        w.priceDate = c.date();
                    });
        } catch (RuntimeException e) {
            log.warn("portfolio analysis: the latest close of {} failed: {}", w.ticker(), e.toString());
        }
        if (w.close == null && !w.held()) {
            w.flags.add("No stored price: it cannot be bought");
        }
    }

    private static Object priceOf(Object level) {
        return level instanceof Map<?, ?> m ? m.get("price") : null;
    }

    private static Double risk(Scorecards cards) {
        return cards.agents().stream().filter(c -> "RISK".equals(c.agent())).map(AgentCard::score)
                .filter(java.util.Objects::nonNull).findFirst().orElse(null);
    }

    /** The plan of the preset with the highest score among those with a complete plan. */
    @SuppressWarnings("unchecked")
    static TradePlan bestRulesPlan(Map<String, Object> summary) {
        if (!(summary.get("summaries") instanceof List<?> list)) {
            return null;
        }
        TradePlan best = null;
        double bestScore = Double.NEGATIVE_INFINITY;
        for (Object o : list) {
            if (!(o instanceof Map<?, ?> m)) {
                continue;
            }
            TradePlan plan = TradePlan.ofRules((Map<String, Object>) m, String.valueOf(m.get("name")));
            double score = TechnicalScore.agentScore(m.get("score"), m.get("maxScore"));
            if (plan.complete() && plan.stopLoss().price() < plan.buy().price()
                    && plan.buy().price() < plan.sell().price() && score > bestScore) {
                best = plan;
                bestScore = score;
            }
        }
        return best;
    }

    private Map<String, Object> synthesisInput(Exchange exchange, RunParameters p, Map<String, Object> capitalDoc,
                                               double capital, List<Work> works) {
        Map<String, Object> in = new LinkedHashMap<>();
        in.put("exchange", exchange.code());
        in.put("universe", p.selected() ? "Stocks selected by the user (" + p.tickers().size() + ")"
                : "Every company of Companies > Fundamentals");
        in.put("capital", Map.of("cash", capitalDoc.get("cash"), "addedCapital", p.addedCapital(), "marketValue",
                capitalDoc.get("marketValue"), "total", capital));
        in.put("steps", p.technical() ? "FUNDAMENTAL then TECHNICAL" : "FUNDAMENTAL only (no technical analysis)");
        in.put("maxStocks", p.maxStocks());
        in.put("maxPositionPct", round1(properties.maxPositionWeight() * 100));
        in.put("maxSectorPct", round1(properties.maxSectorWeight() * 100));
        in.put("kellyFraction", properties.kellyFraction());
        in.put("lotSize", properties.lotSize());
        Map<String, Double> sectors = new LinkedHashMap<>();
        List<Map<String, Object>> holdings = new ArrayList<>();
        List<Map<String, Object>> ideas = new ArrayList<>();
        int rejected = 0;
        for (Work w : works) {
            if (w.held() && w.position.marketValue() != null && capital > 0) {
                sectors.merge(w.step.stock().sector() == null ? "Unclassified" : w.step.stock().sector(),
                        round1(w.position.marketValue() / capital * 100), Double::sum);
            }
            if (!w.held() && !w.fundamentalPass) {
                rejected++;
                continue;
            }
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("ticker", w.ticker());
            m.put("company", w.step.stock().companyName());
            m.put("sector", w.step.stock().sector());
            m.put("price", w.held() ? w.position.lastPrice() : w.close);
            if (w.held()) {
                m.put("shares", w.position.shares());
                m.put("averagePrice", w.position.averagePrice());
                m.put("value", w.position.marketValue());
                m.put("weightPct", w.position.marketValue() == null || capital <= 0 ? null
                        : round1(w.position.marketValue() / capital * 100));
                m.put("gainLossPct", w.position.gainLossPct() == null ? null : round1(w.position.gainLossPct() * 100));
            } else {
                m.put("fundamentalRank", w.step.fundamentalRank());
                m.put("technicalRank", w.step.technicalRank());
            }
            FundamentalAnswer fa = w.fundamental == null ? null : w.fundamental.effective();
            Map<String, Object> f = new LinkedHashMap<>();
            f.put("rulesScore", w.cards == null ? null : w.cards.overall());
            f.put("finalScore", w.fundamentalFinal);
            f.put("verdict", w.fundamentalPass ? "PASS" : "FAIL");
            f.put("thesis", fa == null ? null : fa.thesis());
            f.put("risks", fa == null ? List.of() : fa.risks());
            m.put("fundamental", f);
            TechnicalAnswer ta = w.technical == null ? null : w.technical.effective();
            Map<String, Object> t = new LinkedHashMap<>();
            t.put("rulesScore", w.technicalRules);
            t.put("finalScore", w.technicalFinal);
            t.put("stance", w.technicalStance);
            t.put("plan", w.plan == null ? null : Map.of("entry", w.plan.buy().price(), "stopLoss",
                    w.plan.stopLoss().price(), "target", w.plan.sell().price(), "rewardRisk",
                    w.plan.rewardRisk() == null ? "unknown" : w.plan.rewardRisk()));
            t.put("thesis", ta == null ? null : ta.thesis());
            if (p.technical()) {
                m.put("technical", t);
            }
            m.put("kelly", w.kelly == null ? null : Map.of("weightPct", round1(w.kelly.weight() * 100),
                    "winProbability", round4(w.kelly.p()), "payoff", w.kelly.b() == null ? "unknown"
                            : round4(w.kelly.b())));
            if (!w.flags.isEmpty()) {
                m.put("flags", w.flags);
            }
            (w.held() ? holdings : ideas).add(m);
        }
        in.put("sectorsNowPct", sectors);
        in.put("cashNowPct", capital > 0 ? round1((((Number) capitalDoc.get("cash")).doubleValue() + p.addedCapital())
                / capital * 100) : null);
        in.put("holdings", holdings);
        in.put("ideas", ideas);
        in.put("ideasRejectedByTheFundamentalAnalyst", rejected);
        return in;
    }

