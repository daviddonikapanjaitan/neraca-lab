    private static Map<String, Object> fundamentalDoc(Work w) {
        if (w.cards == null && w.fundamental == null) {
            return null;
        }
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("rulesScore", w.cards == null ? null : w.cards.overall());
        m.put("finalScore", w.fundamentalFinal);
        m.put("verdict", w.fundamentalPass ? "PASS" : "FAIL");
        putOutcome(m, w.fundamental);
        return m;
    }

    private static Map<String, Object> technicalDoc(Work w) {
        if (w.summary == null) {
            return null;
        }
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("rulesScore", w.technicalRules);
        m.put("finalScore", w.technicalFinal);
        m.put("stance", w.technicalStance);
        m.put("plan", w.plan == null ? null : w.plan.toMap());
        m.put("planSource", w.planSource);
        if (w.technical == null) {
            m.put("status", "NOT_ASKED");
            m.put("note", "The fundamental step did not pass it: the technical agent was not asked");
        } else {
            putOutcome(m, w.technical);
        }
        return m;
    }

    private static void putOutcome(Map<String, Object> m, PortfolioAgents.Outcome<?> o) {
        if (o == null) {
            m.put("status", "NOT_ASKED");
            return;
        }
        Object effective = o.effective();
        m.put("status", effective == null ? "RULES_ONLY" : o.revised() != null ? "REVISED" : "ASSESSED");
        m.put("answer", effective);
        if (o.revised() != null) {
            m.put("original", o.original());
        }
        m.put("issues", o.issues());
        m.put("remainingIssues", o.remaining());
        m.put("error", o.error());
    }

    private static String bestThesis(Work w) {
        TechnicalAnswer t = w.technical == null ? null : w.technical.effective();
        FundamentalAnswer f = w.fundamental == null ? null : w.fundamental.effective();
        if (f != null && f.thesis() != null && t != null && t.thesis() != null) {
            return f.thesis() + " " + t.thesis();
        }
        return f != null && f.thesis() != null ? f.thesis() : t != null ? t.thesis() : null;
    }

